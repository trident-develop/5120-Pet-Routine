package org.example.project.data

enum class AnimalCategory {
    Mammal, Bird, Reptile, Amphibian, Ocean, Insect, Arachnid;
}

enum class Region {
    Africa, Europe, Asia, Australia, NorthAmerica, SouthAmerica, Antarctica, Worldwide;
}

enum class Danger(val level: Int) {
    Low(1),
    Medium(2),
    High(3),
    Extreme(4);
}

data class Animal(
    val id: String,
    val name: String,
    val emoji: String,
    val category: AnimalCategory,
    val regions: List<Region>,
    val countries: List<String>,
    val shortFact: String,
    val danger: Danger,
    val behavior: String,
    val habitat: String,
    val diet: String,
    val speedKmh: Int,
    val weightKg: Int,
    val lifespanYears: Int,
    val facts: List<String>,
)

private data class AnimalEntry(
    val id: String,
    val emoji: String,
    val category: AnimalCategory,
    val regions: List<Region>,
    val countries: Pair<List<String>, List<String>>,
    val name: Pair<String, String>,
    val shortFact: Pair<String, String>,
    val danger: Danger,
    val behavior: Pair<String, String>,
    val habitat: Pair<String, String>,
    val diet: Pair<String, String>,
    val speedKmh: Int,
    val weightKg: Int,
    val lifespanYears: Int,
    val facts: Pair<List<String>, List<String>>,
) {
    fun localized(lang: AppLanguage): Animal {
        val en = lang == AppLanguage.English
        return Animal(
            id = id,
            name = if (en) name.first else name.second,
            emoji = emoji,
            category = category,
            regions = regions,
            countries = if (en) countries.first else countries.second,
            shortFact = if (en) shortFact.first else shortFact.second,
            danger = danger,
            behavior = if (en) behavior.first else behavior.second,
            habitat = if (en) habitat.first else habitat.second,
            diet = if (en) diet.first else diet.second,
            speedKmh = speedKmh,
            weightKg = weightKg,
            lifespanYears = lifespanYears,
            facts = if (en) facts.first else facts.second,
        )
    }
}

